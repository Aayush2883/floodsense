export const STRINGS = { en, hi };

export function translate(lang, key, vars) {
  let s = (STRINGS[lang] && STRINGS[lang][key]) ?? en[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.replace(`{${k}}`, String(vars[k]));
  return s;
}
